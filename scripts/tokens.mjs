// Renders replica/design/tokens.json and tokens.dark.json into src/app/tokens.css.
// Run: pnpm tokens. Components use the Tailwind utilities mapped in globals.css, never raw hex.
import { readFileSync, writeFileSync } from "node:fs";

const light = JSON.parse(readFileSync("replica/design/tokens.json", "utf8"));
const dark = JSON.parse(readFileSync("replica/design/tokens.dark.json", "utf8"));

const flat = (obj, prefix = "") =>
  Object.entries(obj).flatMap(([k, v]) => {
    if (k.startsWith("_")) return [];
    const key = prefix ? `${prefix}-${k}` : k;
    return typeof v === "object" && !Array.isArray(v) ? flat(v, key) : [[key, v]];
  });

const colorVars = (c) => flat(c).map(([k, v]) => `  --tk-${k}: ${v};`).join("\n");

const px = (n) => `${n}px`;
const misc = [
  ...Object.entries(light.radius).map(([k, v]) => `  --tk-radius-${k}: ${px(v)};`),
  ...Object.entries(light.shadow).map(([k, v]) => `  --tk-shadow-${k}: ${v};`),
  ...Object.entries(light.motion).map(([k, v]) => `  --tk-motion-${k}: ${v};`),
  ...flat(light.layout).filter(([, v]) => typeof v === "number").map(([k, v]) => `  --tk-layout-${k}: ${px(v)};`),
  ...Object.entries(light.z).map(([k, v]) => `  --tk-z-${k}: ${v};`),
].join("\n");

const css = `/* Generated by scripts/tokens.mjs from replica/design/tokens*.json. Do not edit by hand. */
:root {
${colorVars(light.color)}
${misc}
  color-scheme: light;
}
:root[data-theme="dark"] {
${colorVars(dark.color)}
  --tk-shadow-card: 0 1px 2px rgba(0,0,0,.4), 0 1px 3px rgba(0,0,0,.5);
  --tk-shadow-pop: 0 8px 24px rgba(0,0,0,.5);
  --tk-shadow-float: 0 16px 48px rgba(0,0,0,.6);
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(dark.color)}
    --tk-shadow-card: 0 1px 2px rgba(0,0,0,.4), 0 1px 3px rgba(0,0,0,.5);
    --tk-shadow-pop: 0 8px 24px rgba(0,0,0,.5);
    --tk-shadow-float: 0 16px 48px rgba(0,0,0,.6);
    color-scheme: dark;
  }
}
`;
writeFileSync("src/app/tokens.css", css);
console.log(`src/app/tokens.css: ${css.split("\n").length} lines`);
